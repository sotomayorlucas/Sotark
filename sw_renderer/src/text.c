void draw_text(framebuf_t *fb, int x, int y, const char *s, u32 color) {
    while (*s) {
        const unsigned char c = (unsigned char)*s;
        const u8 *glyph = (c < 128) ? FONT[c] : FONT[0];
        for (int gy = 0; gy < 8; ++gy) {
            const u8 row = glyph[gy];
            for (int gx = 0; gx < 8; ++gx) {
                if (row & (0x80u >> gx)) {
                    framebuf_plot(fb, x + gx, y + gy, color);
                }
            }
        }
        x += 8;
        s++;
    }
}

void draw_text_shadowed(framebuf_t *fb, int x, int y, const char *s, u32 fg) {
    /* Drop shadow para legibilidad. */
    draw_text(fb, x + 1, y + 1, s, 0xFF000000u);
    draw_text(fb, x,     y,     s, fg);
}

void draw_rect(framebuf_t *fb, int x, int y, int w, int h, u32 color) {
    int x0 = x, y0 = y, x1 = x + w, y1 = y + h;
    if (x0 < 0) x0 = 0;
    if (y0 < 0) y0 = 0;
    if (x1 > fb->w) x1 = fb->w;
    if (y1 > fb->h) y1 = fb->h;
    for (int yy = y0; yy < y1; ++yy) {
        u32 *row = fb->color + (size_t)yy * fb->pitch_pixels;
        for (int xx = x0; xx < x1; ++xx) row[xx] = color;
    }
}
